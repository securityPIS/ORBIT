export function portById(id) {
  return PORTS.find((p) => p.id === id) || null
}

/** Estimated toll in USD for `vessel` transiting `chokepoint`. */
export function tollFor(chokepoint, vessel) {
  const rate = chokepoint.tollPerDwt?.[vessel.class]
  if (!rate) return 0
  return Math.round((vessel.dwt * rate) / 1000) * 1000
}

/**
 * Which of the chokepoint's limits `vessel` breaks, if any.
 * Returns [] when the vessel can transit.
 */
export function limitBreaches(chokepoint, vessel) {
  const l = chokepoint.limits || {}
  const out = []
  if (l.draft && vessel.draft > l.draft) out.push({ kind: 'draft', need: vessel.draft, limit: l.draft, unit: 'm' })
  if (l.beam && vessel.beam > l.beam) out.push({ kind: 'beam', need: vessel.beam, limit: l.beam, unit: 'm' })
  if (l.loa && vessel.loa > l.loa) out.push({ kind: 'length', need: vessel.loa, limit: l.loa, unit: 'm' })
  if (l.airDraft && vessel.airDraft > l.airDraft) out.push({ kind: 'air draft', need: vessel.airDraft, limit: l.airDraft, unit: 'm' })
  return out
}
