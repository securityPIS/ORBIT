// ---------------------------------------------------------------------------
// Reference data for the ship route planner.
//
// The 1° water mask in oceanGrid.js handles open ocean, but it is too coarse
// for canals, straits and narrow seas — a 30 km wide strait simply is not
// there at 1°. LANES below hand-draw those passages as explicit navigable
// polylines, and CHOKEPOINTS attach the transit rules (size limits, tolls,
// transit time) that make one route viable and another not.
//
// Dimensions and tolls are published/industry figures rounded to planning
// accuracy. They are decision-support estimates, not a substitute for the
// canal authority's own tariff or a charterer's voyage calculation.
// ---------------------------------------------------------------------------

// A `gates` entry is [lng, lat, radiusNm]. Inside that circle the open-water
// grid is cut, so traffic has to follow the lane and therefore has to pass the
// chokepoint node where the size limits are enforced. Without this, any strait
// wide enough for the 1° grid to resolve — the Bosphorus, the Great Belt, Sunda
// — would silently let an oversized ship through beside the lane. Passages with
// no size limit need no gate, and canals are already sealed by their isthmus.

